LOWER_BETTER = {"TO"}
YAHOO_DEFAULT_MODS = {"PTS": 1, "REB": 1.2, "AST": 1.5, "ST": 3, "BLK": 3, "TO": -1}

MORE_NAMES = ["Splash Bros Inc.", "Board Men Get Paid", "Bucket Getters", "Pick and Pop", "Fast Break FC",
              "Zone Defense", "Glass Cleaners", "The Bench Mob"]

