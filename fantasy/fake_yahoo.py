def league_key(slug: str) -> str:
    return f"478.l.{70000 + list(LEAGUES).index(slug)}"


# ------------------------------------------------------------------ Yahoo JSON shapes
def settings_json(slug: str) -> dict:
    cfg = LEAGUES[slug]
    stats = []
    names = cfg.get("cats") or list(cfg["mods"])
    for nm in names:
        stats.append({"stat": {"stat_id": STAT[nm], "enabled": "1", "name": nm, "display_name": nm,
                               "sort_order": "0" if nm in LOWER_BETTER else "1", "position_type": "P"}})
    if "FG%" in names:   # Yahoo lists the made/attempted pair as a display-only stat
        stats.append({"stat": {"stat_id": 9004003, "enabled": "1", "name": "FGM/A", "display_name": "FGM/A",
                               "sort_order": "1", "position_type": "P", "is_only_display_stat": "1"}})
    settings = {"stat_categories": {"stats": stats}, "roster_positions": []}
    if "mods" in cfg:
        settings["stat_modifiers"] = {"stats": [{"stat": {"stat_id": str(STAT[k]), "value": str(v)}}
                                                for k, v in cfg["mods"].items()]}
    return {"fantasy_content": {"league": [
        {"league_key": league_key(slug), "name": cfg["name"], "scoring_type": cfg["fmt"],
         "num_teams": cfg["n"]},
        {"settings": [settings]}]}}


def _reported(slug: str) -> list[str]:
    cfg = LEAGUES[slug]
    return cfg.get("cats") or list(cfg["mods"])


def scoreboard_json(slug: str, rows: pd.DataFrame) -> dict:
    """One week, carrying only what Yahoo sends for this league's scoring."""
    names = _reported(slug)
    cfg = LEAGUES[slug]
    col = {"PTS": "PTS", "REB": "REB", "AST": "AST", "ST": "STL", "BLK": "BLK", "TO": "TOV",
           "3PTM": "FG3M", "FGM": "FGM"}
    pct = lambda m, a: "" if a == 0 else f"{m / a:.3f}".lstrip("0")
    stat = lambda sid, v: {"stat": {"coverage_type": "week", "stat_id": str(sid), "value": v}}
    matchups = {}
    for i, (mid, grp) in enumerate(rows.groupby("matchup_id", sort=False)):
        teams = {}
        for j, (_, r) in enumerate(grp.iterrows()):
            ss = []
            for nm in names:
                if nm == "FG%":
                    ss += [stat(9004003, f"{int(r['FGM'])}/{int(r['FGA'])}"), stat(5, pct(r["FGM"], r["FGA"]))]
                elif nm == "FT%":
                    ss += [stat(9007006, f"{int(r['FTM'])}/{int(r['FTA'])}"), stat(8, pct(r["FTM"], r["FTA"]))]
                elif nm == "3PT%":
                    ss += [stat(9010009, f"{int(r['FG3M'])}/{int(r['FG3A'])}"), stat(11, pct(r["FG3M"], r["FG3A"]))]
                elif nm == "A/T":
                    ss += [stat(20, f"{r['AST'] / r['TOV']:.2f}" if r["TOV"] else "")]
                elif nm in ("DD", "TD", "OREB"):
                    ss += [stat(STAT[nm], str(int(r["games"] // 9)))]
                else:
                    ss += [stat(STAT[nm], str(int(r[col[nm]])))]
            block = [[{"team_key": r["team_key"]}, {"team_id": r["team_key"].split(".")[-1]},
                      {"name": r["team_name"]}],
                     {"team_stats": {"coverage_type": "week", "week": str(r["week"]), "stats": ss}},
                     {"team_remaining_games": {"coverage_type": "week", "week": str(r["week"]), "total": {
                         "remaining_games": int(r["remaining_games"]), "live_games": int(r["live_games"]),
                         "completed_games": int(r["games"])}}}]
            if "mods" in cfg:
                pts = sum(float(v) * float(r[col[k]]) for k, v in cfg["mods"].items() if k in col)
                block.insert(2, {"team_points": {"coverage_type": "week", "total": f"{pts:.1f}"}})
            teams[str(j)] = {"team": block}
        teams["count"] = len(grp)
        first = grp.iloc[0]
        matchups[str(i)] = {"matchup": {"week": str(first["week"]), "week_start": first["week_start"],
                                        "week_end": first["week_end"], "status": first["status"],
                                        "is_playoffs": "0", "is_consolation": "0", "0": {"teams": teams}}}
    matchups["count"] = len(matchups)
    return {"fantasy_content": {"league": [{"league_key": league_key(slug)},
                                           {"scoreboard": {"week": str(rows["week"].iloc[0]),
                                                           "0": {"matchups": matchups}}}]}}


def users_leagues_json(slugs: list[str]) -> dict:
    """``users;use_login=1/games;game_codes=nba/leagues`` for an account in ``slugs``."""
    leagues = {str(i): {"league": [{"league_key": league_key(s), "league_id": league_key(s).split(".")[-1],
                                    "name": LEAGUES[s]["name"], "season": "2026", "num_teams": LEAGUES[s]["n"],
                                    "scoring_type": LEAGUES[s]["fmt"], "is_finished": 0,
                                    "logo_url": False}]}
               for i, s in enumerate(slugs)}
    leagues["count"] = len(slugs)
    return {"fantasy_content": {"users": {"0": {"user": [{"guid": "FAKEGUID"}, {"games": {"0": {"game": [
        {"game_key": "478", "code": "nba", "season": "2026"}, {"leagues": leagues}]}, "count": 1}}]},
        "count": 1}}}


# ------------------------------------------------------------------ league + source
class FakeLeague:
    """Implements the YahooLeague interface from a demo bundle, via Yahoo's JSON shapes."""

    def __init__(self, slug: str, latency: float = 0.0):
        cfg = LEAGUES[slug]
        self.slug, self.cfg, self.latency = slug, cfg, latency
        self.key = league_key(slug)
        b = demo.make_league(seed=7 + list(LEAGUES).index(slug), n_teams=cfg["n"],
                             completed_weeks=cfg.get("completed", 9),
                             team_names=demo.TEAM_NAMES + MORE_NAMES)
        old = demo.LEAGUE_PREFIX
        swap = lambda s: s.str.replace(old, self.key, regex=False) if s.dtype == object else s
        for k in ("teams", "team_weeks", "rosters", "transactions"):
            df = b[k].copy()
            for c in ("team_key", "opponent_key"):
                if c in df:
                    df[c] = swap(df[c])
            b[k] = df
        self.b = b
        self._weeks = {int(w): g.reset_index(drop=True) for w, g in b["team_weeks"].groupby("week")}
        self.calls = 0

    def _wait(self):
        self.calls += 1
        if self.latency:
            time.sleep(self.latency)

    def meta(self) -> LeagueMeta:
        self._wait()
        m = self.b["meta"]
        return LeagueMeta(league_key=self.key, name=self.cfg["name"], season="2026",
                          scoring_type=self.cfg["fmt"], num_teams=self.cfg["n"], current_week=m.current_week,
                          start_week=1, end_week=m.end_week, playoff_start_week=m.playoff_start_week,
                          num_playoff_teams=min(6, self.cfg["n"] // 2 * 2 - 2 or 2), roster_size=13,
                          scoring=scoring_from_raw_settings(settings_json(self.slug)))

    def teams(self):
        self._wait()
        return self.b["teams"]

    def scoreboard(self, week: int) -> pd.DataFrame:
        self._wait()
        if self.cfg["fmt"] in ("roto", "point"):
            raise RuntimeError("roto leagues have no matchups")
        rows = self._weeks.get(int(week))
        if rows is None:
            raise RuntimeError("no such week")
        return parse_scoreboard(scoreboard_json(self.slug, rows))

    def standings(self):
        self._wait()
        t = self.b["teams"]
        rng = np.random.default_rng(len(t))
        pts = np.sort(rng.uniform(30, 100, len(t)))[::-1].round(1)
        return pd.DataFrame({"team_key": t["team_key"], "team_name": t["team_name"],
                             "rank": range(1, len(t) + 1), "wins": 0, "losses": 0, "ties": 0, "points": pts})

    def transactions(self):
        self._wait()
        return self.b["transactions"]

    def rosters(self, team_keys):
        self._wait()
        return self.b["rosters"]

    def free_agents(self):
        self._wait()
        return self.b["free_agents"]


class FakeSource(Source):
    """A live-style Source (is_demo False) on a FakeLeague, with demo NBA data."""

    def __init__(self, slug: str, latency: float = 0.0):
        super().__init__(FakeLeague(slug, latency), None)

    def players(self, season: str, last_n_games: int = 0) -> pd.DataFrame:
        from fantasy import nba_data
        b = self.live.b
        return b["players"] if season == nba_data.season_for(self.today()) else b["players_prior"]

    def schedule(self, season: str) -> pd.DataFrame:
        return self.live.b["schedule"]

    def today(self):
        tw = self.live.b["team_weeks"]
        live = tw[tw["status"] == "midevent"]
        if live.empty:
            live = tw[tw["status"] == "preevent"]
        return (pd.Timestamp(live.iloc[0]["week_start"]) + pd.Timedelta(days=3)).date()


@dataclass
class FakeUser:
    """Stands in for auth.UserSession (no tokens, never expires)."""
    leagues: list = field(default_factory=list)
    rotated: bool = False

    def ensure_fresh(self):
        return self

    def token_is_valid(self, now=None):
        return True


def fake_user(slugs: list[str] | None = None) -> FakeUser:
    from fantasy.yahoo_client import parse_user_leagues
    return FakeUser(parse_user_leagues(users_leagues_json(slugs or list(LEAGUES))))


def seed_session(state, slugs: list[str] | None = None, latency: float = 0.0, sources: dict | None = None):
    """Sign a Streamlit session in as a fake user whose leagues are fake leagues.

    ``sources`` lets a long-running server build each fake league once and share it,
    the way a real server shares nothing heavier than a token per session."""
    slugs = slugs or list(LEAGUES)
    if "user" not in state:
        state["user"] = fake_user(slugs)
        state["sources"] = dict(sources) if sources is not None else \
            {league_key(s): FakeSource(s, latency) for s in slugs}
